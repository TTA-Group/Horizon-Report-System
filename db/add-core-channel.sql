-- ย้ายการผูกบัญชีไลน์มาเป็นกุญแจกลางขององค์กร
--
-- เดิมระบบแจ้งปัญหาใช้ channel_key = 'report' เป็นของตัวเอง พนักงานจึงต้องลงทะเบียนใหม่
-- ทุกครั้งที่มีระบบใหม่ ทั้งที่ทุกระบบอยู่บน LINE OA เดียวกันของบริษัท และ userId ของไลน์
-- ผูกกับ OA ไม่ได้ผูกกับตัวระบบ อยู่ OA เดียวกันจึงเป็น userId เดียวกันอยู่แล้ว
--
-- เปลี่ยนเป็น 'core' หมายถึง "ผูกกับไลน์ของบริษัทแล้ว" ระบบไหนบน OA นี้ก็อ่านแถวเดียวกันนี้ได้
-- ลงทะเบียนครั้งเดียว ใช้ได้ทั้งระบบแจ้งปัญหา ระบบจองคิวนวด และระบบอื่นที่จะมาต่อ
--
-- ปลอดภัยกับข้อจำกัด UNIQUE ทั้งสองตัวของตาราง เพราะยังไม่มีแถวไหนใช้ 'core' มาก่อน
-- รันซ้ำได้ ครั้งที่สองจะไม่มีแถวไหนเข้าเงื่อนไข

UPDATE line_accounts SET channel_key = 'core' WHERE channel_key = 'report';

